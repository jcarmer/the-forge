import { createHash } from "node:crypto";
import type { Manifest } from "../schema.js";

export const FACTS_START = "<!-- SANDBOX-FACTS:START (machine-owned; do not edit) -->";
export const FACTS_END = "<!-- SANDBOX-FACTS:END -->";

/** The facts block the drift healthcheck compares against live state. */
export function factsOf(m: Manifest) {
  return {
    services: m.services.map((s) => ({ name: s.name, port: s.port })).sort((a, b) => a.name.localeCompare(b.name)),
    volumes: Object.keys(m.volumes).sort(),
    toolchain: m.toolchain,
    ollama: { primary: m.ollama.primaryModel, extra: m.ollama.extraModels },
    tailscale: { hostname: m.network.tailscaleHostname, tag: m.network.tailscaleTag },
    providers: m.providers.map((p) => p.name),
  };
}

export function factsHash(m: Manifest): string {
  return createHash("sha256").update(JSON.stringify(factsOf(m))).digest("hex").slice(0, 16);
}

/** Renders SETUP.md: an LLM-readable description of how to rebuild everything from scratch. */
export function renderSetupMd(m: Manifest): string {
  const svc = m.services.map((s) => `| ${s.name} | ${s.port} | ${s.description} |`).join("\n");
  const vols = Object.entries(m.volumes).map(([k, v]) => `| ${k} | ${v.mount} | ${v.description} |`).join("\n");
  const providers = m.providers.map((p) => `${p.priority}. ${p.name}${p.usageCommand ? ` (usage: \`${p.usageCommand}\`)` : ""}`).join("\n");
  return `# SETUP.md: Rebuild the AI Sandbox From Scratch

> GENERATED by \`sandboxctl generate\`. This file is written for an LLM operator. If you are an LLM: follow it step by step, explain each step to the user in plain language, and ask before anything destructive.

## 1. What this is
A Docker stack on a Windows 11 desktop (RTX 3080) that runs coding agents in isolation. The container is its **own Tailscale node** (\`${m.network.tailscaleHostname}\`, tag \`${m.network.tailscaleTag}\`). No ports are published on the Windows host and the desktop is never exposed.

## 2. Prerequisites (Windows)
1. Docker Desktop with WSL 2 backend and NVIDIA GPU support (verify: \`docker run --rm --gpus all nvidia/cuda:12.4.1-base-ubuntu22.04 nvidia-smi\`).
2. Node.js LTS (the bootstrap script installs it via winget if missing).
3. A Tailscale auth key tagged \`${m.network.tailscaleTag}\` (reusable, with the tag allowed in your ACL \`tagOwners\`).
4. A fine-grained GitHub PAT: Contents read/write on only the needed repos. Branch protection on \`${m.git.mainBranch}\`.
5. Secrets file \`.env\` next to the compose file: \`${m.network.authKeyEnv}\`, \`GH_TOKEN\`, \`ANTHROPIC_API_KEY\` (optional). Never commit it.

## 3. Build and run
\`\`\`powershell
./bootstrap.ps1          # installs/checks Node, installs dependencies, builds CLI
npx tsx src/cli.ts init  # guided: checks prerequisites, creates .env
npx tsx src/cli.ts up    # generates files, builds the image, starts the stack
npx tsx src/cli.ts clone # clones manifest repos into /projects
npx tsx src/cli.ts doctor
\`\`\`

### One-time logins on a new machine
Run \`npx tsx src/cli.ts auth-status\` to see which logins are missing and their exact 1-line commands. (Setting \`CLAUDE_CODE_OAUTH_TOKEN\` from \`claude setup-token\` in \`.env\` makes Claude zero-touch.)

### Managing The Forge from inside the container
All environment configuration lives in \`sandbox.config.ts\` and idempotent TypeScript modules in \`src/provision/steps.ts\` (run automatically on boot via \`provision\`). Edit those inside \`/opt/the-forge\`, then run \`node /opt/the-forge/dist/src/cli.js rebuild\` to recreate the container from within.

## 4. Services (reachable on the tailnet node, not on Windows localhost)
| Service | Port | Purpose |
|---|---|---|
${svc}

## 5. Volumes
| Volume | Container mount | Purpose |
|---|---|---|
${vols}

Repos live on a Linux volume (\`/projects\`), not a Windows mount. GitHub is the sync point.

## 6. Toolchain
CUDA image \`${m.toolchain.cudaImage}\`, .NET ${m.toolchain.dotnetChannel}, Node ${m.toolchain.nodeMajor}, Godot ${m.toolchain.godotVersion} (**headless only**, used by TBE), Python ${m.toolchain.pythonVersion}. Also: Ollama, Antigravity CLI, Claude Code, T3 Code, OpenCode, Caddy, VS Code CLI.

## 7. Local LLM
Primary model \`${m.ollama.primaryModel}\`${m.ollama.extraModels.length ? `, extras: ${m.ollama.extraModels.join(", ")}` : ""}. The \`ollama-helper\` MCP server and the rules/skills/tools/plugins from \`${m.paths.metaDir}\` are live-mounted (edits apply without a rebuild).

## 8. Git model
\`${m.git.mainBranch}\` (user-owned, managed in GitComet on Windows) → \`${m.git.integrationBranch}\` (integration) → \`${m.git.taskBranchPrefix}*\` (one worktree per task). Merge only, never force-push. \`${m.git.mainBranch}\` is merged into \`${m.git.integrationBranch}\` automatically; conflicts become an agent task. Finished tasks pass a gate (build, typecheck, tests, standards review) before merging.

## 9. Provider routing (preference order, adjusted by live usage)
${providers}

Usage limits come in three scopes: \`5h\`, \`weekly\`, \`model_weekly\`. Prefer Ollama; for cloud providers spend quota that resets soonest.

## 10. VS Code access
\`code tunnel\` in the container (browser or desktop VS Code). One-time login: \`sandboxctl tunnel-login\`.

## 11. Common problems and fixes
| Symptom | Fix |
|---|---|
| \`docker\` not found | Install Docker Desktop (WSL 2). Then re-run \`init\`. |
| GPU not visible in container | Update NVIDIA driver, restart Docker Desktop, run the GPU test in section 2. |
| Container not on tailnet | Tailscale key expired or tag not allowed. Create a new key, update \`.env\`, run \`up\`. |
| Pushes fail | \`GH_TOKEN\` missing or expired. Update \`.env\`, run \`up\`. |
| Buddy keeps restarting | \`sandboxctl logs buddy\`, then fix the error shown. The watchdog restarts it every 3s. |
| Model missing | It is pulled automatically on start; check disk space and \`sandboxctl logs ollama\`. |
| VS Code tunnel offline | \`sandboxctl tunnel-login\`. |

## 12. Healthcheck
\`sandboxctl healthcheck --drift\` compares live Docker state with this file's facts block and the manifest; it also checks for newer qwen-coder models (and recommends model upgrades) and re-tests the \`/usage\` parsers. It proposes diffs and never applies them without approval.

${FACTS_START}
\`\`\`json
${JSON.stringify({ hash: factsHash(m), ...factsOf(m) }, null, 2)}
\`\`\`
${FACTS_END}
`;
}
